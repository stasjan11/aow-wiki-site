  function buildL9Card(b) {
    const card = el('div', 'build-card');
    const head = el('div', 'build-head');
    head.appendChild(el('span', 'build-n', b.n));
    head.appendChild(el('span', 'build-title', b.title));
    head.appendChild(el('span', 'build-tag', b.tag));
    card.appendChild(head);
    card.appendChild(p(b.same));

    const cols = el('div', 'build-cols');

    const left = el('div', 'build-col');
    left.appendChild(h3('Апгрейды предметов (предок = база + грань)'));
    const ul = el('div', 'build-list');
    for (const [id, why] of b.up) {
      const row = el('div', 'build-item');
      row.appendChild(itemLink(id));
      row.appendChild(pn('span', 'build-rowtext', ' — ' + why));
      ul.appendChild(row);
    }
    left.appendChild(ul);
    cols.appendChild(left);

    const right = el('div', 'build-col');
    right.appendChild(h3('Остаётся базой'));
    const rl = el('div', 'build-list');
    for (const [id, why] of b.keep) {
      const row = el('div', 'build-item');
      row.appendChild(itemLink(id));
      row.appendChild(pn('span', 'build-rowtext', ' — ' + why));
      rl.appendChild(row);
    }
    right.appendChild(rl);
    cols.appendChild(right);

    card.appendChild(cols);
    card.appendChild(pn('div', 'build-note', b.note));
    return card;
  }

