  // ------------------------------------------------------------- разметка

  function linkNode(token) {
    const m = /^\[\[item:([^\]|]+)\|([^\]]+)\]\]$/.exec(token);
    if (!m) return el('span', '', token);
    return itemLink(m[1], m[2]);
  }

  function itemLink(id, label) {
    const it = ITEMS[id];
    const a = el('span', 'faq-link');
    const name = label || (it && it.name) || id;
    if (it) a.appendChild(iconNode(it, 'icon-xs'));
    a.appendChild(el('span', 'faq-link-name', name));
    if (it) {
      a.onclick = () => go(isConsumable(it) ? 'consumables' : 'items', id);
      a.title = `Открыть «${name}» (${id})`;
    }
    return a;
  }

  function rich(text) {
    const frag = [];
    const re = /(\*\*[^*]+\*\*|`[^`]+`|\[\[item:[^\]|]+\|[^\]]+\]\])/g;
    let last = 0;
    let m;
    while ((m = re.exec(text))) {
      if (m.index > last) frag.push(document.createTextNode(text.slice(last, m.index)));
      const token = m[0];
      if (token.startsWith('**')) frag.push(el('strong', '', token.slice(2, -2)));
      else if (token.startsWith('`')) frag.push(el('code', 'inline-code', token.slice(1, -1)));
      else frag.push(linkNode(token));
      last = m.index + token.length;
    }
    if (last < text.length) frag.push(document.createTextNode(text.slice(last)));
    return frag;
  }

  function pn(tag, cls, text) {
    const n = el(tag, cls);
    if (text != null) for (const part of rich(text)) n.appendChild(part);
    return n;
  }

